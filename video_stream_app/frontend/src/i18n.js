const initialLanguage = (() => {
  const saved = localStorage.getItem(STORAGE_KEY)
  return saved === 'en' || saved === 'zh' ? saved : FALLBACK_LANG
})()

const language = ref(initialLanguage)

function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => {
    return params[key] ?? `{${key}}`
  })
}

function setLanguage(nextLanguage) {
  if (nextLanguage !== 'zh' && nextLanguage !== 'en') return
  language.value = nextLanguage
  localStorage.setItem(STORAGE_KEY, nextLanguage)
}

function t(key, params) {
  const table = messages[language.value] || messages[FALLBACK_LANG]
  const fallbackTable = messages[FALLBACK_LANG]
  return interpolate(table[key] || fallbackTable[key] || key, params)
}

function windowLabel(windowId, rangeEndId = null) {
  if (rangeEndId != null) {
    return language.value === 'zh'
      ? `${t('app.windowPrefix')} ${windowId}-${rangeEndId}`
      : `${t('app.windowPrefix')} ${windowId}-${rangeEndId}`
  }
  return `${t('app.windowPrefix')} ${windowId}`
}

export function useI18n() {
  return {
    language,
    languageLabel: computed(() => t('lang.label')),
    setLanguage,
    t,
    windowLabel,
  }
}
